export type Dataset = keyof typeof DATASETS;

export function isDataset(value: string | undefined): value is Dataset {
  return value !== undefined && Object.hasOwn(DATASETS, value);
}

/** Whether a dataset may be installed: every one but those of a publisher held for permission. */
export function datasetEnabled(key: string): boolean {
  return !isDataset(key) || publisherEnabled(DATASETS[key].publisher);
}
