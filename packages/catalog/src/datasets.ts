/*
 * Every dataset this catalog serves: one publisher's body of data, read by one
 * or more feeds. The dataset says what the data is, who published it and under
 * what terms; a feed says how and how often a part of it is read. Two feeds
 * belong to the same dataset when they describe the same things, by the same
 * identifiers, under the same terms — Carris's stops, vehicles and GTFS are one
 * dataset; IPMA's forecasts and earthquakes share nothing and are two.
 *
 * A key never changes: it is what a dataset's page is addressed by. It opens
 * with its publisher's key, which a test holds it to.
 */
import { publisherEnabled, type Publisher } from "./publishers";

import type { Licence } from "./licences";

export interface DatasetDescription {
  title: string;
  description: string;
  /** Who made the data, a key of `PUBLISHERS`: never the portal it was read from. */
  publisher: Publisher;
  /** The terms the publisher states for it, a key of `LICENCES`, or `source-terms` when they state none. */
  licence: Licence;
  /** How the publisher asks to be credited, when they say. */
  attribution?: string;
  /** What the catalog groups and filters by, each a key of `TOPICS`. */
  topics: string[];
}

